// Safe getter function to get pregenerated audio base64 on-demand without memory bottlenecks
export function getPregeneratedAudio(guideId: string, lang: 'en' | 'mni'): string | null {
  try {
    // Lazily load pregenerated audio store
    // eslint-disable-next-line @typescript-eslint/no-var-requires
    const pregeneratedStore = require('./pregeneratedAudio.json');
    if (pregeneratedStore && pregeneratedStore[guideId]) {
      return lang === 'mni'
        ? pregeneratedStore[guideId].audioMni || null
        : pregeneratedStore[guideId].audioEn || null;
    }
  } catch (err) {
    console.warn('Lazy audio lookup notice:', err);
  }
  return null;
}
